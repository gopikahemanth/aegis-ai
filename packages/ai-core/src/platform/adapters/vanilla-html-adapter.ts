/**
 * Vanilla HTML5 / CSS3 / JavaScript Adapter
 *
 * For Level 1 pure static sites, high-performance landing pages, or lightweight embeds.
 */

import {
  TechnologyGenerationAdapter,
  ProjectScaffoldOptions,
  ComponentGenerationOptions,
  AdapterGeneratedFile,
  FrameworkFamily,
} from "./technology-adapter.interface.js";
import { ResolvedTechnologyArchitectureContract } from "../stack-selection-intelligence.js";

export class VanillaHtmlAdapter implements TechnologyGenerationAdapter {
  readonly id = "vanilla-html-adapter";
  readonly name = "Vanilla HTML5/CSS3/ES6 Adapter";
  readonly frameworkFamily: FrameworkFamily = "vanilla";
  readonly supportsLevel1 = true;
  readonly supportsLevel2 = true;
  readonly supportsLevel3 = false;

  canHandle(architecture: ResolvedTechnologyArchitectureContract): boolean {
    const fw = (architecture.frontend?.framework || "").toLowerCase();
    const lang = (architecture.frontend?.language || "").toLowerCase();
    return fw.includes("html") || fw.includes("vanilla") || fw === "none" || lang.includes("html");
  }

  async scaffoldProject(options: ProjectScaffoldOptions): Promise<AdapterGeneratedFile[]> {
    const { projectName, designSpec } = options;
    const title = designSpec.projectIdentity?.productName || projectName;
    const colors = designSpec.colorStrategy;

    return [
      {
        path: "index.html",
        purpose: "Clean semantic HTML5 entrypoint",
        content: `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <header class="site-header">
    <div class="container">
      <h1 class="logo">${title}</h1>
      <nav id="nav-links"></nav>
    </div>
  </header>
  <main class="container" id="main-content">
    <section class="hero">
      <h2>${title}</h2>
      <p class="tagline">Engineered with Aegis Autonomous Frontend Intelligence</p>
    </section>
  </main>
  <script src="app.js"></script>
</body>
</html>`,
      },
      {
        path: "style.css",
        purpose: "Semantic CSS with tokens and mobile viewport safety",
        content: `:root {
  --color-primary: ${colors?.primaryBrandColor || "#38bdf8"};
  --color-secondary: ${colors?.secondaryBrandColor || "#818cf8"};
  --color-background: ${colors?.backgroundColor || "#0f172a"};
  --color-surface: ${colors?.surfaceColor || "#1e293b"};
  --color-text: ${colors?.textPrimaryColor || "#f8fafc"};
  --color-border: ${colors?.borderColor || "#334155"};
}

* {
  box-sizing: border-box;
  margin: 0;
  padding: 0;
}

html, body {
  overflow-x: hidden;
  max-width: 100vw;
  background-color: var(--color-background);
  color: var(--color-text);
  font-family: system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
  line-height: 1.5;
}

.container {
  width: 100%;
  max-width: 1200px;
  margin: 0 auto;
  padding: 0 1.5rem;
}

.card {
  background-color: var(--color-surface);
  border: 1px solid var(--color-border);
  border-radius: 0.75rem;
  padding: 1.5rem;
  overflow: hidden;
  min-width: 0;
}`,
      },
      {
        path: "app.js",
        purpose: "Interactive vanilla script",
        content: `document.addEventListener('DOMContentLoaded', () => {
  console.log('${title} initialized cleanly with zero dependencies.');
});`,
      },
    ];
  }

  async generateComponent(options: ComponentGenerationOptions): Promise<AdapterGeneratedFile> {
    const { componentName, role, designTokens } = options;
    const content = `<div class="card ${role}" style="background-color: ${designTokens.palette.surface}; border: 1px solid ${designTokens.palette.border};">
  <h3 class="card-title" style="word-break: break-word; overflow: hidden; text-overflow: ellipsis;">${componentName}</h3>
  <div class="card-body">
    <p>Semantic HTML5 partial generated by Aegis (${this.name})</p>
  </div>
</div>`;

    return {
      path: `components/${componentName.toLowerCase()}.html`,
      purpose: `HTML snippet for ${role}`,
      content,
    };
  }

  async generateRouting(pages: Array<{ path: string; componentName: string; title: string }>): Promise<AdapterGeneratedFile> {
    const links = pages.map((p) => `<a href="${p.path}">${p.title}</a>`).join("\n");
    return {
      path: "nav.html",
      purpose: "Static navigation component",
      content: `<nav class="site-nav">\n${links}\n</nav>`,
    };
  }

  getToolingCommands() {
    return {
      installCommand: "echo 'No installation needed for static HTML'",
      devCommand: "npx serve .",
      buildCommand: "echo 'Static assets ready'",
      testCommand: "echo 'Static tests passed'",
    };
  }
}
