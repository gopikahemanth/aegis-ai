/**
 * Svelte / SvelteKit Frontend Generation Adapter
 */

import {
  TechnologyGenerationAdapter,
  ProjectScaffoldOptions,
  ComponentGenerationOptions,
  AdapterGeneratedFile,
  FrameworkFamily,
} from "./technology-adapter.interface.js";
import { ResolvedTechnologyArchitectureContract } from "../stack-selection-intelligence.js";

export class SvelteAdapter implements TechnologyGenerationAdapter {
  readonly id = "svelte-vite-adapter";
  readonly name = "Svelte + Vite Adapter";
  readonly frameworkFamily: FrameworkFamily = "svelte";
  readonly supportsLevel1 = true;
  readonly supportsLevel2 = true;
  readonly supportsLevel3 = true;

  canHandle(architecture: ResolvedTechnologyArchitectureContract): boolean {
    const fw = (architecture.frontend?.framework || "").toLowerCase();
    return fw.includes("svelte");
  }

  async scaffoldProject(options: ProjectScaffoldOptions): Promise<AdapterGeneratedFile[]> {
    const { projectName, architecture, designSpec } = options;
    const isTs = (architecture.frontend?.language || "").toLowerCase().includes("typescript");

    const title = designSpec.projectIdentity?.productName || projectName;
    const colors = designSpec.colorStrategy;

    const files: AdapterGeneratedFile[] = [
      {
        path: "package.json",
        purpose: "Svelte project configuration",
        content: JSON.stringify(
          {
            name: projectName,
            version: "0.1.0",
            private: true,
            type: "module",
            scripts: {
              dev: "vite",
              build: "vite build",
              preview: "vite preview",
            },
            dependencies: {
              svelte: "^4.2.19",
              "lucide-svelte": "^0.436.0",
            },
            devDependencies: {
              "@sveltejs/vite-plugin-svelte": "^3.1.2",
              vite: "^5.4.1",
              ...(isTs ? { typescript: "^5.5.3", "svelte-check": "^3.8.5" } : {}),
              tailwindcss: "^3.4.10",
              autoprefixer: "^10.4.20",
              postcss: "^8.4.41",
            },
          },
          null,
          2
        ),
      },
      {
        path: "index.html",
        purpose: "HTML entrypoint",
        content: `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${title}</title>
    <link rel="stylesheet" href="/src/app.css" />
  </head>
  <body class="bg-slate-900 text-slate-100 antialiased min-h-screen">
    <div id="app"></div>
    <script type="module" src="/src/main.${isTs ? "ts" : "js"}"></script>
  </body>
</html>`,
      },
      {
        path: `src/main.${isTs ? "ts" : "js"}`,
        purpose: "Svelte mount target",
        content: `import App from './App.svelte';
import './app.css';

const app = new App({
  target: document.getElementById('app')!,
});

export default app;`,
      },
      {
        path: "src/app.css",
        purpose: "Design tokens and styles",
        content: `@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  --color-primary: ${colors?.primaryBrandColor || "#38bdf8"};
  --color-secondary: ${colors?.secondaryBrandColor || "#818cf8"};
  --color-background: ${colors?.backgroundColor || "#0f172a"};
  --color-surface: ${colors?.surfaceColor || "#1e293b"};
  --color-text: ${colors?.textPrimaryColor || "#f8fafc"};
}

html, body {
  overflow-x: hidden;
  max-width: 100vw;
  background-color: var(--color-background);
  color: var(--color-text);
}`,
      },
    ];

    return files;
  }

  async generateComponent(options: ComponentGenerationOptions): Promise<AdapterGeneratedFile> {
    const { componentName, role, designTokens } = options;
    const content = `<script lang="ts">
  export let title: string = '${componentName}';
</script>

<div
  class="${role === "card" ? "rounded-xl border p-6 backdrop-blur-md min-w-0 overflow-hidden" : "w-full"}"
  style="background-color: ${designTokens.palette.surface}; border-color: ${designTokens.palette.border}; color: ${designTokens.palette.text};"
>
  <h3 class="text-xl font-bold tracking-tight break-words truncate">{title}</h3>
  <div class="mt-4 text-sm text-slate-300">
    <slot>Svelte component generated by Aegis Autonomous Frontend Intelligence (${this.name})</slot>
  </div>
</div>
`;

    return {
      path: `src/lib/components/${componentName}.svelte`,
      purpose: `Svelte component for ${role}`,
      content,
    };
  }

  async generateRouting(pages: Array<{ path: string; componentName: string; title: string }>): Promise<AdapterGeneratedFile> {
    const content = `<script lang="ts">
  import Navbar from './lib/components/Navbar.svelte';
  let currentPath = window.location.pathname;
</script>

<div class="min-h-screen flex flex-col">
  <Navbar />
  <main class="flex-1 w-full max-w-7xl mx-auto px-4 py-8">
    <h1 class="text-3xl font-bold">App Navigation</h1>
    <p class="mt-2 text-slate-400">Current view: {currentPath}</p>
  </main>
</div>
`;

    return {
      path: "src/App.svelte",
      purpose: "Svelte root application shell",
      content,
    };
  }

  getToolingCommands() {
    return {
      installCommand: "npm install",
      devCommand: "npm run dev",
      buildCommand: "npm run build",
      testCommand: "npm run test",
    };
  }
}
