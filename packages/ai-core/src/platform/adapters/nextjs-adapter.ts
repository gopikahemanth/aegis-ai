/**
 * Next.js (App Router / React) Adapter
 */

import {
  TechnologyGenerationAdapter,
  ProjectScaffoldOptions,
  ComponentGenerationOptions,
  AdapterGeneratedFile,
  FrameworkFamily,
} from "./technology-adapter.interface.js";
import { ResolvedTechnologyArchitectureContract } from "../stack-selection-intelligence.js";

export class NextJsAdapter implements TechnologyGenerationAdapter {
  readonly id = "nextjs-adapter";
  readonly name = "Next.js App Router Adapter";
  readonly frameworkFamily: FrameworkFamily = "nextjs";
  readonly supportsLevel1 = true;
  readonly supportsLevel2 = true;
  readonly supportsLevel3 = true;

  canHandle(architecture: ResolvedTechnologyArchitectureContract): boolean {
    const fw = (architecture.frontend?.framework || "").toLowerCase();
    return fw.includes("next");
  }

  async scaffoldProject(options: ProjectScaffoldOptions): Promise<AdapterGeneratedFile[]> {
    const { projectName, designSpec } = options;
    const title = designSpec.projectIdentity?.productName || projectName;
    const colors = designSpec.colorStrategy;

    return [
      {
        path: "package.json",
        purpose: "Next.js dependencies and scripts",
        content: JSON.stringify(
          {
            name: projectName,
            version: "0.1.0",
            private: true,
            scripts: {
              dev: "next dev",
              build: "next build",
              start: "next start",
              lint: "next lint",
            },
            dependencies: {
              next: "^14.2.5",
              react: "^18.3.1",
              "react-dom": "^18.3.1",
              "lucide-react": "^0.436.0",
            },
            devDependencies: {
              typescript: "^5.5.3",
              "@types/node": "^20.14.14",
              "@types/react": "^18.3.3",
              "@types/react-dom": "^18.3.0",
              tailwindcss: "^3.4.10",
              postcss: "^8.4.41",
              autoprefixer: "^10.4.20",
            },
          },
          null,
          2
        ),
      },
      {
        path: "app/layout.tsx",
        purpose: "Next.js root layout with design tokens",
        content: `import type { Metadata } from 'next';
import './globals.css';

export const metadata: Metadata = {
  title: '${title}',
  description: 'Generated by Aegis Autonomous Frontend Intelligence',
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en" className="dark">
      <body className="min-h-screen bg-slate-900 text-slate-100 antialiased overflow-x-hidden">
        {children}
      </body>
    </html>
  );
}`,
      },
      {
        path: "app/globals.css",
        purpose: "Tailwind and CSS variables",
        content: `@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  --color-primary: ${colors?.primaryBrandColor || "#38bdf8"};
  --color-secondary: ${colors?.secondaryBrandColor || "#818cf8"};
  --color-background: ${colors?.backgroundColor || "#0f172a"};
  --color-surface: ${colors?.surfaceColor || "#1e293b"};
  --color-text: ${colors?.textPrimaryColor || "#f8fafc"};
}`,
      },
    ];
  }

  async generateComponent(options: ComponentGenerationOptions): Promise<AdapterGeneratedFile> {
    const { componentName, role, designTokens } = options;
    const content = `import React from 'react';

export default function ${componentName}() {
  return (
    <section
      className="${role === "card" ? "rounded-xl border p-6 min-w-0 overflow-hidden" : "w-full py-8"}"
      style={{
        backgroundColor: '${designTokens.palette.surface}',
        borderColor: '${designTokens.palette.border}',
        color: '${designTokens.palette.text}'
      }}
    >
      <h2 className="text-2xl font-bold tracking-tight break-words truncate">${componentName}</h2>
      <p className="mt-2 text-sm text-slate-400">Next.js React Server Component</p>
    </section>
  );
}
`;

    return {
      path: `components/${componentName}.tsx`,
      purpose: `Next.js component for ${role}`,
      content,
    };
  }

  async generateRouting(pages: Array<{ path: string; componentName: string; title: string }>): Promise<AdapterGeneratedFile> {
    const content = `import Link from 'next/link';

export default function HomePage() {
  return (
    <main className="max-w-7xl mx-auto px-4 py-12">
      <h1 className="text-4xl font-extrabold tracking-tight">Welcome</h1>
      <nav className="mt-6 flex gap-4">
${pages
  .map((p) => `        <Link href="${p.path}" className="text-indigo-400 hover:underline">${p.title}</Link>`)
  .join("\n")}
      </nav>
    </main>
  );
}
`;

    return {
      path: "app/page.tsx",
      purpose: "Next.js App Router root page",
      content,
    };
  }

  getToolingCommands() {
    return {
      installCommand: "npm install",
      devCommand: "npm run dev",
      buildCommand: "npm run build",
      testCommand: "npm run test",
    };
  }
}
