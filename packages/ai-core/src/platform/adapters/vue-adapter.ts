/**
 * Vue 3 (Composition API / Vite) Frontend Generation Adapter
 */

import {
  TechnologyGenerationAdapter,
  ProjectScaffoldOptions,
  ComponentGenerationOptions,
  AdapterGeneratedFile,
  FrameworkFamily,
} from "./technology-adapter.interface.js";
import { ResolvedTechnologyArchitectureContract } from "../stack-selection-intelligence.js";

export class VueAdapter implements TechnologyGenerationAdapter {
  readonly id = "vue-vite-adapter";
  readonly name = "Vue 3 + Vite Adapter";
  readonly frameworkFamily: FrameworkFamily = "vue";
  readonly supportsLevel1 = true;
  readonly supportsLevel2 = true;
  readonly supportsLevel3 = true;

  canHandle(architecture: ResolvedTechnologyArchitectureContract): boolean {
    const fw = (architecture.frontend?.framework || "").toLowerCase();
    return fw.includes("vue") && !fw.includes("nuxt");
  }

  async scaffoldProject(options: ProjectScaffoldOptions): Promise<AdapterGeneratedFile[]> {
    const { projectName, architecture, designSpec } = options;
    const isTs = (architecture.frontend?.language || "").toLowerCase().includes("typescript");
    const scriptLang = isTs ? ' lang="ts"' : "";

    const title = designSpec.projectIdentity?.productName || projectName;
    const colors = designSpec.colorStrategy;

    const files: AdapterGeneratedFile[] = [
      {
        path: "package.json",
        purpose: "Vue 3 project dependencies and scripts",
        content: JSON.stringify(
          {
            name: projectName,
            version: "0.1.0",
            private: true,
            type: "module",
            scripts: {
              dev: "vite",
              build: isTs ? "vue-tsc && vite build" : "vite build",
              preview: "vite preview",
            },
            dependencies: {
              vue: "^3.4.38",
              "vue-router": "^4.4.3",
              "lucide-vue-next": "^0.436.0",
            },
            devDependencies: {
              "@vitejs/plugin-vue": "^5.1.2",
              vite: "^5.4.1",
              ...(isTs ? { typescript: "^5.5.3", "vue-tsc": "^2.1.4" } : {}),
              tailwindcss: "^3.4.10",
              autoprefixer: "^10.4.20",
              postcss: "^8.4.41",
            },
          },
          null,
          2
        ),
      },
      {
        path: "index.html",
        purpose: "HTML entrypoint",
        content: `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${title}</title>
    <link rel="stylesheet" href="/src/style.css" />
  </head>
  <body class="bg-slate-900 text-slate-100 antialiased min-h-screen">
    <div id="app"></div>
    <script type="module" src="/src/main.${isTs ? "ts" : "js"}"></script>
  </body>
</html>`,
      },
      {
        path: `src/main.${isTs ? "ts" : "js"}`,
        purpose: "Vue app bootstrap",
        content: `import { createApp } from 'vue';
import App from './App.vue';
import router from './router';
import './style.css';

const app = createApp(App);
app.use(router);
app.mount('#app');`,
      },
      {
        path: "src/style.css",
        purpose: "Global design tokens and utility styling",
        content: `@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  --color-primary: ${colors?.primaryBrandColor || "#38bdf8"};
  --color-secondary: ${colors?.secondaryBrandColor || "#818cf8"};
  --color-background: ${colors?.backgroundColor || "#0f172a"};
  --color-surface: ${colors?.surfaceColor || "#1e293b"};
  --color-text: ${colors?.textPrimaryColor || "#f8fafc"};
}

html, body {
  overflow-x: hidden;
  max-width: 100vw;
  background-color: var(--color-background);
  color: var(--color-text);
}`,
      },
    ];

    return files;
  }

  async generateComponent(options: ComponentGenerationOptions): Promise<AdapterGeneratedFile> {
    const { componentName, role, designTokens } = options;
    const content = `<script setup lang="ts">
defineProps<{
  title?: string
}>()
</script>

<template>
  <div
    class="${role === "card" ? "rounded-xl border p-6 backdrop-blur-md min-w-0 overflow-hidden" : "w-full"}"
    :style="{
      backgroundColor: '${designTokens.palette.surface}',
      borderColor: '${designTokens.palette.border}',
      color: '${designTokens.palette.text}'
    }"
  >
    <h3 class="text-xl font-bold tracking-tight break-words truncate">{{ title || '${componentName}' }}</h3>
    <div class="mt-4 text-sm text-slate-300">
      <slot>Vue SFC generated by Aegis Autonomous Frontend Intelligence (${this.name})</slot>
    </div>
  </div>
</template>
`;

    return {
      path: `src/components/${componentName}.vue`,
      purpose: `Vue Single File Component for ${role}`,
      content,
    };
  }

  async generateRouting(pages: Array<{ path: string; componentName: string; title: string }>): Promise<AdapterGeneratedFile> {
    const routes = pages
      .map(
        (p) =>
          `  { path: '${p.path}', name: '${p.componentName}', component: () => import('./views/${p.componentName}.vue') },`
      )
      .join("\n");

    const content = `import { createRouter, createWebHistory } from 'vue-router';

const routes = [
${routes}
];

export const router = createRouter({
  history: createWebHistory(),
  routes,
});

export default router;
`;

    return {
      path: "src/router/index.ts",
      purpose: "Vue Router configuration",
      content,
    };
  }

  getToolingCommands() {
    return {
      installCommand: "npm install",
      devCommand: "npm run dev",
      buildCommand: "npm run build",
      testCommand: "npm run test",
    };
  }
}
