/**
 * InteractionProvenanceTracker & PipelineProvenanceLedger
 *
 * Implements Invariant 3: Interaction Provenance & Native Interaction Ratio (NIR).
 *
 * Architecture:
 *   1. IMMUTABLE BASELINE — captured exactly once, immediately after CoderAgent
 *      finishes and before any sanitizer/post-processing runs. Never modified.
 *
 *   2. PIPELINE PROVENANCE LEDGER — a separate, append-only record that tracks
 *      every source file created or modified after the baseline was captured.
 *      Each entry records: relative path, authoring stage, agent name, content
 *      hash, and pipeline stage index. The ledger cannot retroactively change
 *      what was in the baseline.
 *
 *   3. NIR AUDIT — compares the current src/ tree against the immutable baseline
 *      and the ledger to produce an auditable provenance report.
 *
 * Handler classification (per file):
 *   CODER_NATIVE       — file in immutable baseline, content unchanged
 *   NATIVE (modified)  — handler signature present in baseline entry
 *   DESIGN_PIPELINE    — file NOT in baseline but registered in ledger as DESIGN_PIPELINE
 *   SANITIZER_INJECTED — file NOT in baseline, NOT in ledger (or ledger stage = STRUCTURAL_FIXER)
 *   EXCLUDED_FROM_NIR  — test files / design-system utility boilerplate (not product code)
 *
 * NIR formula:
 *   NIR = nativeHandlers / (nativeHandlers + sanitizerInjectedHandlers)
 *   (pipelineNativeHandlers are tracked separately and not included in either term)
 *
 * Policy enforcement (FinalSuccessGate):
 *   STANDARD          — fails only if sanitizerInjectedHandlers > 0
 *   STRICT_UNASSISTED — fails if sanitizerInjectedHandlers > 0 OR pipelineNativeHandlers > 0
 *                       (every post-baseline handler must be zero for unassisted certification)
 */

import { existsSync, readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

// ─────────────────────────────────────────────────────────────────────────────
// Shared types
// ─────────────────────────────────────────────────────────────────────────────

export type PipelineStage =
  | "CODER_AGENT"       // Generated by CoderAgent (present in immutable baseline)
  | "DESIGN_PIPELINE"   // Generated by ExperienceArchitect / GenericExperienceGenerator
  | "STRUCTURAL_FIXER"  // Added by FastSanitizer / DeterministicProjectFixer for repairs
  | "TEST_GENERATOR";   // Added by TestGeneratorAgent

export interface PipelineLedgerEntry {
  relPath: string;
  stage: PipelineStage;
  agent: string;
  pipelineStageIndex: number;
  contentHash: string;
  registeredAt: string;
}

export interface ComponentHandlerInfo {
  file: string;
  componentName: string;
  handlerType: string;
  signature: string;
  source: "CODER_NATIVE" | "SANITIZER_INJECTED" | "HEALER_REPAIRED" | "DESIGN_PIPELINE";
}

export interface FileProvenanceSnapshot {
  filePath: string;
  contentHash: string;
  handlers: ComponentHandlerInfo[];
}

export interface InteractionBaselineArtifact {
  generationId: string;
  capturedAt: string;
  sourceHash: string;
  totalFiles: number;
  totalNativeHandlers: number;
  files: Array<[string, FileProvenanceSnapshot]>;
}

export interface InteractionProvenanceReport {
  generationId?: string;
  capturedAt?: string;
  sourceHash?: string;
  nativeHandlers: number;
  sanitizerInjectedHandlers: number;
  pipelineNativeHandlers: number;        // from DESIGN_PIPELINE stage (not CODER_NATIVE, not injected)
  sanitizerRepairedComponents: string[];
  nativeInteractionFailures: number;
  nir: number; // 0.0 - 1.0 (excludes pipelineNative from both terms)
  filesAudited: number;
  details: Array<{
    file: string;
    nativeCount: number;
    injectedCount: number;
    pipelineNativeCount: number;
    handlers: string[];
  }>;
  summary: string;
}

// ─────────────────────────────────────────────────────────────────────────────
// PipelineProvenanceLedger
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Append-only ledger that records every source file created or modified after
 * the immutable CoderAgent baseline was captured.
 *
 * The ledger DOES NOT modify the baseline. It is a separate audit trail that
 * lets the NIR audit correctly classify non-baseline files by their authoring
 * stage without resetting the original provenance evidence.
 */
export class PipelineProvenanceLedger {
  private static ledgerFile(projectRoot: string): string {
    return join(projectRoot, ".aegis", "pipeline-provenance-ledger.json");
  }

  /**
   * Register a file that was created or substantially modified after the
   * CoderAgent baseline. This does NOT touch the baseline.
   */
  public static register(
    projectRoot: string,
    relPath: string,
    stage: PipelineStage,
    agent: string,
    content: string,
    pipelineStageIndex = 99,
  ): void {
    const norm = relPath.replace(/\\/g, "/");
    const entries = this.load(projectRoot);
    const idx = entries.findIndex(e => e.relPath === norm);
    const entry: PipelineLedgerEntry = {
      relPath: norm,
      stage,
      agent,
      pipelineStageIndex,
      contentHash: this.hashString(content),
      registeredAt: new Date().toISOString(),
    };
    if (idx >= 0) {
      entries[idx] = entry;
    } else {
      entries.push(entry);
    }
    try {
      const aegisDir = join(projectRoot, ".aegis");
      if (!existsSync(aegisDir)) mkdirSync(aegisDir, { recursive: true });
      writeFileSync(this.ledgerFile(projectRoot), JSON.stringify(entries, null, 2), "utf8");
    } catch { /* non-fatal */ }
  }

  /**
   * Load all ledger entries for a project.
   */
  public static load(projectRoot: string): PipelineLedgerEntry[] {
    const path = this.ledgerFile(projectRoot);
    if (!existsSync(path)) return [];
    try {
      const parsed = JSON.parse(readFileSync(path, "utf8"));
      return Array.isArray(parsed) ? parsed : [];
    } catch { return []; }
  }

  /**
   * Build a fast lookup map from relPath → PipelineLedgerEntry.
   */
  public static loadMap(projectRoot: string): Map<string, PipelineLedgerEntry> {
    const map = new Map<string, PipelineLedgerEntry>();
    for (const entry of this.load(projectRoot)) {
      map.set(entry.relPath, entry);
    }
    return map;
  }

  private static hashString(str: string): string {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
      hash = ((hash << 5) - hash) + str.charCodeAt(i);
      hash |= 0;
    }
    return hash.toString(16);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// InteractionProvenanceTracker
// ─────────────────────────────────────────────────────────────────────────────

export class InteractionProvenanceTracker {
  private static baselineSnapshots = new Map<string, Map<string, FileProvenanceSnapshot>>();
  private static baselineMetadata = new Map<string, { generationId: string; capturedAt: string; sourceHash: string }>();

  public static hasBaseline(projectRoot: string): boolean {
    if (this.baselineSnapshots.has(projectRoot) && (this.baselineSnapshots.get(projectRoot)?.size || 0) > 0) {
      return true;
    }
    const baselineFile = join(projectRoot, ".aegis", "interaction-baseline.json");
    return existsSync(baselineFile);
  }

  /**
   * Reset in-memory baseline cache. Useful between test runs or pipeline resets.
   */
  public static reset(projectRoot?: string): void {
    if (projectRoot) {
      this.baselineSnapshots.delete(projectRoot);
      this.baselineMetadata.delete(projectRoot);
    } else {
      this.baselineSnapshots.clear();
      this.baselineMetadata.clear();
    }
  }

  /**
   * Capture the IMMUTABLE baseline immediately after CoderAgent finishes
   * and BEFORE any sanitizer or post-processing scripts execute.
   *
   * This method MUST NOT be called with force=true after the sanitizer runs.
   * The baseline is a one-time snapshot of CoderAgent-authored code.
   */
  public static captureBaseline(
    projectRoot: string,
    options?: { generationId?: string; force?: boolean }
  ): Map<string, FileProvenanceSnapshot> {
    if (!options?.force && this.baselineSnapshots.has(projectRoot) && (this.baselineSnapshots.get(projectRoot)?.size || 0) > 0) {
      return this.baselineSnapshots.get(projectRoot)!;
    }
    const srcDir = join(projectRoot, "src");
    const snapshotMap = new Map<string, FileProvenanceSnapshot>();
    const generationId = options?.generationId || `gen_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`;
    const capturedAt = new Date().toISOString();

    if (!existsSync(srcDir)) {
      this.baselineSnapshots.set(projectRoot, snapshotMap);
      return snapshotMap;
    }

    const files = this.collectSourceFiles(srcDir);
    let combinedContent = "";
    for (const f of files.sort()) {
      const rel = relative(projectRoot, f).replace(/\\/g, "/");
      const content = readFileSync(f, "utf8");
      combinedContent += rel + ":" + content;
      const handlers = this.extractHandlers(content, rel, "CODER_NATIVE");
      snapshotMap.set(rel, {
        filePath: rel,
        contentHash: this.hashString(content),
        handlers,
      });
    }

    const sourceHash = this.hashString(combinedContent);
    this.baselineSnapshots.set(projectRoot, snapshotMap);
    this.baselineMetadata.set(projectRoot, { generationId, capturedAt, sourceHash });
    const totalHandlers = this.countTotalHandlers(snapshotMap);
    console.log(`[InteractionProvenance] 📸 Baseline captured at CoderAgent boundary for ${snapshotMap.size} files with ${totalHandlers} native interactive handlers. (Gen ID: ${generationId}, Source Hash: ${sourceHash})`);

    // Persist immutable baseline to .aegis/interaction-baseline.json
    try {
      const aegisDir = join(projectRoot, ".aegis");
      if (!existsSync(aegisDir)) mkdirSync(aegisDir, { recursive: true });
      const artifact: InteractionBaselineArtifact = {
        generationId,
        capturedAt,
        sourceHash,
        totalFiles: snapshotMap.size,
        totalNativeHandlers: totalHandlers,
        files: Array.from(snapshotMap.entries()),
      };
      writeFileSync(join(aegisDir, "interaction-baseline.json"), JSON.stringify(artifact, null, 2), "utf8");
    } catch {}

    return snapshotMap;
  }

  /**
   * Audit interaction provenance after post-processing/sanitization is complete.
   *
   * Classification logic (per non-excluded file):
   * 1. File in baseline, content unchanged  → all handlers = CODER_NATIVE
   * 2. File in baseline, content changed    → handler-signature diff (native vs injected)
   * 3. File NOT in baseline, in ledger as DESIGN_PIPELINE → pipelineNative (not injected)
   * 4. File NOT in baseline, in ledger as STRUCTURAL_FIXER / unknown ledger stage → injected
   * 5. File NOT in baseline, NOT in ledger  → injected (unknown origin)
   */
  public static audit(
    projectRoot: string,
    options?: {
      nativeInteractionFailures?: number;
      sanitizerTouchedFiles?: string[];
    }
  ): InteractionProvenanceReport {
    const srcDir = join(projectRoot, "src");
    let baseline = this.baselineSnapshots.get(projectRoot);
    let meta = this.baselineMetadata.get(projectRoot);

    if (!baseline || baseline.size === 0) {
      const baselineFile = join(projectRoot, ".aegis", "interaction-baseline.json");
      if (existsSync(baselineFile)) {
        try {
          const raw = JSON.parse(readFileSync(baselineFile, "utf8"));
          if (raw && !Array.isArray(raw) && Array.isArray(raw.files)) {
            baseline = new Map(raw.files);
            meta = { generationId: raw.generationId, capturedAt: raw.capturedAt, sourceHash: raw.sourceHash };
            this.baselineMetadata.set(projectRoot, meta);
          } else if (Array.isArray(raw)) {
            baseline = new Map(raw);
          }
          if (baseline) {
            this.baselineSnapshots.set(projectRoot, baseline);
          }
        } catch {}
      }
    }

    // If still no baseline, prefer loading an existing on-disk report over
    // fabricating an all-injected result
    if (!baseline || baseline.size === 0) {
      const existingReport = this.loadReport(projectRoot);
      if (existingReport && existingReport.nativeHandlers > 0) {
        return existingReport;
      }
    }

    // Load pipeline provenance ledger for classifying post-baseline files
    const ledger = PipelineProvenanceLedger.loadMap(projectRoot);

    baseline = baseline || new Map<string, FileProvenanceSnapshot>();
    const currentFiles = existsSync(srcDir) ? this.collectSourceFiles(srcDir) : [];

    let nativeCount = 0;
    let injectedCount = 0;
    let pipelineNativeCount = 0;
    const repairedComponents = new Set<string>(options?.sanitizerTouchedFiles || []);
    const details: InteractionProvenanceReport["details"] = [];

    for (const f of currentFiles) {
      const rel = relative(projectRoot, f).replace(/\\/g, "/");

      // Skip test files and design-system utility components — these are not
      // CoderAgent feature interaction code and must not influence NIR.
      // Excluded paths are reported with zero counts for full audit transparency.
      if (InteractionProvenanceTracker.isExcludedFromNIR(rel)) {
        details.push({ file: rel, nativeCount: 0, injectedCount: 0, pipelineNativeCount: 0, handlers: ["[EXCLUDED_FROM_NIR]"] });
        continue;
      }

      const content = readFileSync(f, "utf8");
      const currentHandlers = this.extractHandlers(content, rel, "CODER_NATIVE");
      const baselineEntry = baseline.get(rel);

      let fileNative = 0;
      let fileInjected = 0;
      let filePipelineNative = 0;
      const handlerSummaries: string[] = [];

      if (!baselineEntry) {
        // ── File was NOT present at baseline capture ──────────────────────────
        const ledgerEntry = ledger.get(rel);

        if (ledgerEntry?.stage === "DESIGN_PIPELINE") {
          // Registered explicitly as a design-pipeline page (e.g. GenericExperienceGenerator).
          // This is intentional product authorship from the design system, but it was NOT
          // authored by the CoderAgent. It is tracked separately as pipelineNative.
          // Under STRICT_UNASSISTED this will prevent NIR certification.
          filePipelineNative = currentHandlers.length;
          pipelineNativeCount += filePipelineNative;
          if (currentHandlers.length > 0) repairedComponents.add(rel);
          for (const h of currentHandlers) {
            handlerSummaries.push(`[DESIGN_PIPELINE] ${h.handlerType}`);
          }
        } else {
          // Unknown post-baseline file: could be from STRUCTURAL_FIXER or any unregistered agent.
          // Classified as SANITIZER_INJECTED regardless.
          fileInjected = currentHandlers.length;
          injectedCount += fileInjected;
          if (currentHandlers.length > 0) repairedComponents.add(rel);
          const stageLabel = ledgerEntry ? `STRUCTURAL_FIXER:${ledgerEntry.agent}` : "UNKNOWN_ORIGIN";
          for (const h of currentHandlers) {
            handlerSummaries.push(`[INJECTED:${stageLabel}] ${h.handlerType}`);
          }
        }
      } else {
        // ── File WAS in the baseline ──────────────────────────────────────────
        const baselineContentHash = baselineEntry.contentHash;
        const currentHash = this.hashString(content);

        if (baselineContentHash === currentHash) {
          // Untouched: all handlers are CoderAgent-native
          fileNative = currentHandlers.length;
          nativeCount += fileNative;
          for (const h of currentHandlers) {
            handlerSummaries.push(`[NATIVE] ${h.handlerType}`);
          }
        } else {
          // File was modified after baseline capture: diff handlers
          repairedComponents.add(rel);
          const baselineSignatures = new Set(baselineEntry.handlers.map(h => h.signature));

          for (const h of currentHandlers) {
            if (baselineSignatures.has(h.signature)) {
              fileNative++;
              nativeCount++;
              handlerSummaries.push(`[NATIVE] ${h.handlerType}`);
            } else {
              fileInjected++;
              injectedCount++;
              handlerSummaries.push(`[INJECTED:POST_BASELINE_MODIFICATION] ${h.handlerType}`);
            }
          }
        }
      }

      details.push({
        file: rel,
        nativeCount: fileNative,
        injectedCount: fileInjected,
        pipelineNativeCount: filePipelineNative,
        handlers: handlerSummaries,
      });
    }

    // NIR excludes pipelineNative from both numerator and denominator.
    // It strictly measures: CoderAgent-authored handlers vs sanitizer-injected handlers.
    const totalForNIR = nativeCount + injectedCount;
    const nir = totalForNIR > 0 ? Number((nativeCount / totalForNIR).toFixed(3)) : 1.0;
    const nativeFailures = options?.nativeInteractionFailures ?? 0;

    const pipelineSuffix = pipelineNativeCount > 0
      ? `, Design-Pipeline: ${pipelineNativeCount}`
      : "";
    const summary = `Native Interaction Ratio: ${nir.toFixed(2)} (Native: ${nativeCount}, Injected: ${injectedCount}${pipelineSuffix}, Repaired Components: ${repairedComponents.size}, Interaction Failures: ${nativeFailures})`;

    const report: InteractionProvenanceReport = {
      generationId: meta?.generationId,
      capturedAt: meta?.capturedAt,
      sourceHash: meta?.sourceHash,
      nativeHandlers: nativeCount,
      sanitizerInjectedHandlers: injectedCount,
      pipelineNativeHandlers: pipelineNativeCount,
      sanitizerRepairedComponents: Array.from(repairedComponents),
      nativeInteractionFailures: nativeFailures,
      nir,
      filesAudited: currentFiles.length,
      details,
      summary,
    };

    try {
      const aegisDir = join(projectRoot, ".aegis");
      if (!existsSync(aegisDir)) mkdirSync(aegisDir, { recursive: true });
      writeFileSync(join(aegisDir, "interaction-provenance.json"), JSON.stringify(report, null, 2), "utf8");
    } catch {}

    return report;
  }

  /**
   * Load existing interaction provenance report from .aegis/interaction-provenance.json if present.
   */
  public static loadReport(projectRoot: string): InteractionProvenanceReport | null {
    const reportPath = join(projectRoot, ".aegis", "interaction-provenance.json");
    if (!existsSync(reportPath)) return null;
    try {
      return JSON.parse(readFileSync(reportPath, "utf8"));
    } catch {
      return null;
    }
  }

  /**
   * Determines whether a source file should be excluded from NIR audit.
   *
   * Excluded categories (not CoderAgent feature interaction authorship):
   * - Test files (src/__tests__/, *.test.tsx, *.spec.tsx) — created by TestGeneratorAgent
   * - Design-system utility components (src/components/ui/) — sanitizer boilerplate
   * - Pure design-token / shared utility files with no domain interaction logic
   *
   * Excluded files are reported in audit details with zero counts for transparency.
   * The exclusion paths are intentionally narrow: only well-known non-product
   * infrastructure patterns. Any product handler in an excluded path is a design error.
   */
  public static isExcludedFromNIR(relPath: string): boolean {
    const norm = relPath.replace(/\\/g, "/");
    // Test infrastructure (not product interactions)
    if (/[/\\]__tests__[/\\]/.test(norm)) return true;
    if (/\.(test|spec)\.(tsx|jsx|ts|js)$/.test(norm)) return true;
    // Design-system utility boilerplate (sanitizer-generated, not feature code)
    if (/^src[/\\]components[/\\]ui[/\\]/.test(norm)) return true;
    if (/^src[/\\]design-system[/\\]components[/\\]/.test(norm)) return true;
    return false;
  }

  private static extractHandlers(
    code: string,
    file: string,
    source: ComponentHandlerInfo["source"]
  ): ComponentHandlerInfo[] {
    const handlers: ComponentHandlerInfo[] = [];
    const compName = file.split("/").pop()?.replace(/\.[^.]+$/, "") || "Unknown";

    const eventRegex = /\b(on(?:Click|Change|Submit|KeyDown|KeyUp|Select|Toggle|Input))\s*=\s*\{([^}]+)}/g;
    let match: RegExpExecArray | null;

    while ((match = eventRegex.exec(code)) !== null) {
      const handlerType = match[1];
      const snippet = match[2].trim().slice(0, 40);
      handlers.push({
        file,
        componentName: compName,
        handlerType,
        signature: `${compName}:${handlerType}:${snippet}`,
        source,
      });
    }

    const stateRegex = /\bconst\s*\[\s*([a-zA-Z0-9_]+)\s*,\s*set([a-zA-Z0-9_]+)\s*\]\s*=\s*useState/g;
    while ((match = stateRegex.exec(code)) !== null) {
      const varName = match[1];
      handlers.push({
        file,
        componentName: compName,
        handlerType: "useState",
        signature: `${compName}:state:${varName}`,
        source,
      });
    }

    return handlers;
  }

  private static collectSourceFiles(dir: string): string[] {
    const results: string[] = [];
    try {
      const entries = readdirSync(dir, { withFileTypes: true });
      for (const e of entries) {
        const full = join(dir, e.name);
        if (e.isDirectory()) {
          results.push(...this.collectSourceFiles(full));
        } else if (/\.(tsx|jsx)$/i.test(e.name)) {
          results.push(full);
        }
      }
    } catch {}
    return results;
  }

  private static hashString(str: string): string {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
      hash = ((hash << 5) - hash) + str.charCodeAt(i);
      hash |= 0;
    }
    return hash.toString(16);
  }

  private static countTotalHandlers(map: Map<string, FileProvenanceSnapshot>): number {
    let count = 0;
    for (const snap of map.values()) {
      count += snap.handlers.length;
    }
    return count;
  }
}
