/**
 * Python / FastAPI Backend Generation Adapter
 */

import {
  TechnologyGenerationAdapter,
  ProjectScaffoldOptions,
  ComponentGenerationOptions,
  AdapterGeneratedFile,
  FrameworkFamily,
} from "./technology-adapter.interface.js";
import { ResolvedTechnologyArchitectureContract } from "../stack-selection-intelligence.js";

export class FastApiAdapter implements TechnologyGenerationAdapter {
  readonly id = "fastapi-adapter";
  readonly name = "Python FastAPI Backend Adapter";
  readonly frameworkFamily: FrameworkFamily = "backend-python";
  readonly supportsLevel1 = false;
  readonly supportsLevel2 = true;
  readonly supportsLevel3 = true;

  canHandle(architecture: ResolvedTechnologyArchitectureContract): boolean {
    const be = (architecture.backend?.framework || "").toLowerCase();
    return be.includes("fastapi");
  }

  async scaffoldProject(options: ProjectScaffoldOptions): Promise<AdapterGeneratedFile[]> {
    const { projectName, architecture, designSpec } = options;
    const title = designSpec.projectIdentity?.productName || projectName;

    return [
      {
        path: "requirements.txt",
        purpose: "Python dependencies",
        content: `fastapi>=0.109.0
uvicorn[standard]>=0.27.0
pydantic>=2.6.0
sqlalchemy>=2.0.25
python-dotenv>=1.0.0
pytest>=8.0.0
httpx>=0.26.0
`,
      },
      {
        path: "main.py",
        purpose: "FastAPI application entrypoint with CORS and health endpoints",
        content: `"""
${title} - FastAPI API Server
Generated by Aegis Autonomous Backend Intelligence
"""
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from routers import api_router

app = FastAPI(
    title="${title} API",
    version="1.0.0",
    docs_url="/docs",
    redoc_url="/redoc",
)

# CORS Middleware configuration
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://localhost:3000"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(api_router, prefix="/api/v1")

@app.get("/health")
def health_check():
    return {"status": "ok", "service": "${title}"}

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("main:app", host="0.0.0.0", port=8000, reload=True)
`,
      },
      {
        path: "routers/__init__.py",
        purpose: "Router aggregator",
        content: `from fastapi import APIRouter

api_router = APIRouter()

@api_router.get("/")
def get_root():
    return {"message": "Welcome to ${title} API"}
`,
      },
    ];
  }

  async generateComponent(options: ComponentGenerationOptions): Promise<AdapterGeneratedFile> {
    const { componentName, role } = options;
    const content = `"""
${componentName} Endpoint Router
Generated by Aegis (${this.name}) for ${role}
"""
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel
from typing import List, Optional

router = APIRouter(prefix="/${componentName.toLowerCase()}", tags=["${componentName}"])

class ${componentName}Schema(BaseModel):
    id: Optional[int] = None
    title: str
    description: Optional[str] = None

@router.get("/", response_model=List[${componentName}Schema])
def list_${componentName.toLowerCase()}():
    return [{"id": 1, "title": "Sample ${componentName}", "description": "Auto-generated model"}]

@router.post("/", response_model=${componentName}Schema)
def create_${componentName.toLowerCase()}(payload: ${componentName}Schema):
    return payload
`;

    return {
      path: `routers/${componentName.toLowerCase()}.py`,
      purpose: `FastAPI route handler for ${componentName}`,
      content,
    };
  }

  async generateRouting(pages: Array<{ path: string; componentName: string; title: string }>): Promise<AdapterGeneratedFile> {
    const includes = pages
      .map((p) => `from routers.${p.componentName.toLowerCase()} import router as ${p.componentName.toLowerCase()}_router\napi_router.include_router(${p.componentName.toLowerCase()}_router)`)
      .join("\n");

    const content = `from fastapi import APIRouter

api_router = APIRouter()

${includes}
`;

    return {
      path: "routers/manifest.py",
      purpose: "Aggregated route registrations",
      content,
    };
  }

  getToolingCommands() {
    return {
      installCommand: "pip install -r requirements.txt",
      devCommand: "uvicorn main:app --reload --port 8000",
      buildCommand: "python -m compileall .",
      testCommand: "pytest",
    };
  }
}
